    internal static CultureInfo Culture => CultureInfo.GetCultureInfo(Language == "zh" ? "zh-CN" : Language);

    internal static string Language { get; private set; } = "ar";
    private static Dictionary<string, string> translated = new();

    internal static string T(string original, string? fallback = null)
    {
        if (IsArabic) return original;
        if (!labels.TryGetValue(original, out var label)) return fallback ?? original;
        return translated.TryGetValue(label.Key, out var value) ? value : label.English;
    }

    internal static void Apply(string? language)
    {
        if (language == null || language == "Auto") language = CultureInfo.CurrentUICulture.TwoLetterISOLanguageName;
        Language = language is "ar" or "ja" or "zh" or "fr" or "es" ? language : "en";
        translated = new Dictionary<string, string>();
        if (Language is "ja" or "zh" or "fr" or "es")
        {
            int index = Language == "zh" ? 2 : Language == "fr" ? 3 : 1;
            string name = Language == "es" ? "Spanish.tsv" : "Translations.tsv";
            var file = Application.GetResourceStream(new System.Uri("/" + typeof(App).Assembly.GetName().Name + ";component/" + name, System.UriKind.Relative));
            using var reader = new System.IO.StreamReader(file.Stream);
            while (reader.ReadLine() is string row)
            {
                var cells = row.Split('\t');
                if (cells.Length > index) translated[cells[0]] = cells[index];
            }
        }
        var resources = Application.Current.Resources;
        resources["UiDirection"] = IsArabic ? FlowDirection.RightToLeft : FlowDirection.LeftToRight;
        foreach (var pair in labels) resources[pair.Value.Key] = T(pair.Key);
    }
